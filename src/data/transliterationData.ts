// Helper function to get transliteration for any ayah
export const getAyahTransliteration = (surahId: number, ayahNumber: number): string => {
  const surahData = transliterationData[surahId.toString()];
  if (surahData && surahData[ayahNumber]) {
    return surahData[ayahNumber];
  }
  return `Ayet ${ayahNumber} - Okunuş henüz eklenmemiş`;
};

// Get all available surahs with transliteration
export const getAvailableSurahsWithTransliteration = (): number[] => {
  return Object.keys(transliterationData).map(id => parseInt(id));
};
